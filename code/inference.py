"""Reload the frozen notebook model and predict from engineered pre-race features.

Example:
    python code/inference.py --models output/models --record output/inference_demo_inputs.json --example partial

Input is a JSON dictionary with the numeric feature keys from metadata.json.
History/form/standings are features prepared by the notebook, not raw race IDs.
An omitted/null/nonpositive grid is missing; grid_unassigned is derived from grid.
An explicitly supplied contradictory grid_unassigned flag fails clearly.
Only load model files generated by this project or from another trusted source:
joblib model files are Python pickle artifacts.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Mapping

import joblib
import numpy as np
import pandas as pd


class PodiumPredictor:
    """Load the native selected model and its training-fitted preprocessing."""

    def __init__(self, model_dir: str | Path, model_name: str | None = None):
        self.model_dir = Path(model_dir)
        self.metadata = json.loads((self.model_dir / "metadata.json").read_text(encoding="utf-8"))
        self.features = list(self.metadata["features"])
        self.model_name = model_name or self.metadata["selected_model"]
        self.threshold = float(self.metadata["all_thresholds"][self.model_name])
        self.preprocessor = joblib.load(self.model_dir / "preprocessing.joblib")
        if self.preprocessor['features'] != self.features:
            raise ValueError('Model metadata and preprocessing feature order disagree.')
        if self.model_name == "Shallow neural network":
            import os
            os.environ.setdefault('TF_CPP_MIN_LOG_LEVEL', '2')
            from tensorflow import keras
            self.model = keras.models.load_model(self.model_dir / "shallow_neural_network.keras", compile=False)
        else:
            filename = {"Logistic regression": "logistic_regression.joblib",
                        "Random forest": "random_forest.joblib"}.get(self.model_name)
            if filename is None:
                raise ValueError(f"Unsupported exported model: {self.model_name}")
            self.model = joblib.load(self.model_dir / filename)

    def predict_podium(self, record: Mapping[str, Any]) -> dict[str, Any]:
        if not isinstance(record, Mapping):
            raise TypeError("record must be a dictionary of numeric pre-race features.")
        unknown = sorted(set(record) - set(self.features))
        if unknown:
            raise ValueError(f"Unknown feature keys: {unknown}. Allowed keys: {self.features}")
        normalized_record = dict(record)
        raw_grid = normalized_record.get("grid", None)
        if raw_grid is None:
            normalized_grid = np.nan
        else:
            try:
                normalized_grid = float(raw_grid)
            except (TypeError, ValueError) as exc:
                raise ValueError("grid must be a number or null.") from exc
            if not np.isfinite(normalized_grid):
                raise ValueError("grid must be finite or null.")
            if normalized_grid <= 0:
                normalized_grid = np.nan
        derived_grid_flag = int(pd.isna(normalized_grid))
        raw_flag = normalized_record.get("grid_unassigned", None)
        if raw_flag is not None:
            try:
                supplied_flag = float(raw_flag)
            except (TypeError, ValueError) as exc:
                raise ValueError("grid_unassigned must be 0 or 1, matching grid.") from exc
            if not np.isfinite(supplied_flag):
                raise ValueError("grid_unassigned must be finite or null.")
            if supplied_flag != derived_grid_flag:
                raise ValueError(f"grid_unassigned={raw_flag} contradicts grid={raw_grid}; expected {derived_grid_flag}.")
        normalized_record["grid"] = None if pd.isna(normalized_grid) else normalized_grid
        normalized_record["grid_unassigned"] = derived_grid_flag
        values, missing = {}, []
        for feature in self.features:
            value = normalized_record.get(feature)
            if value is None:
                values[feature] = np.nan
                missing.append(feature)
                continue
            try:
                number = float(value)
            except (TypeError, ValueError) as exc:
                raise ValueError(f"{feature} must be a number or null.") from exc
            if not np.isfinite(number):
                raise ValueError(f"{feature} must be finite or null.")
            values[feature] = number
        frame = pd.DataFrame([values], columns=self.features)
        filled = frame.fillna(self.preprocessor['medians']).copy()
        for feature in self.preprocessor['indicator_features']:
            filled['missing_' + feature] = frame[feature].isna().astype(float)
        filled = filled[self.preprocessor['transformed_features']]
        inputs = self.preprocessor['scaler'].transform(filled)
        if self.model_name == "Shallow neural network":
            probability = float(np.asarray(self.model(inputs.astype(np.float32), training=False)).ravel()[0])
        else:
            probability = float(self.model.predict_proba(inputs)[0, 1])
        return {"model": self.model_name, "podium_probability": probability,
                "podium_prediction": int(probability >= self.threshold),
                "threshold": self.threshold, "imputed_features": missing,
                "note": "Missing inputs use training medians and missingness flags."
                if missing else "All engineered inputs supplied."}


def _default_model_dir() -> Path:
    root = Path(__file__).resolve().parents[1]
    for relative in ["output/models", "outputs/models", "artifacts/models"]:
        candidate = root / relative
        if (candidate / "metadata.json").is_file():
            return candidate
    return root / "output" / "models"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models", type=Path, default=_default_model_dir(), help="Directory containing metadata.json and exported models")
    parser.add_argument("--record", type=Path, required=True, help="JSON engineered-feature dictionary or notebook demo inputs JSON")
    parser.add_argument("--example", choices=["complete", "partial", "missing_grid"], help="Select a dictionary from the notebook's demo-inputs file")
    args = parser.parse_args()
    record = json.loads(args.record.read_text(encoding="utf-8"))
    if args.example:
        record = record[args.example]
    print(json.dumps(PodiumPredictor(args.models).predict_podium(record), indent=2))


if __name__ == "__main__":
    main()
